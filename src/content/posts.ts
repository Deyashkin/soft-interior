/** Статьи от новых к старым — порядок вывода в списке. */
export const sortedPosts = [...posts].sort((a, b) =>
  b.publishedAt.localeCompare(a.publishedAt),
);

/** Уникальные рубрики — для перелинковки и подписи в карточках. */
export const postCategories = [...new Set(posts.map((post) => post.category))];

/** Дата в читаемом виде: «14 июля 2026». Intl добавляет « г.» — убираем. */
export function formatPostDate(iso: string) {
  return new Intl.DateTimeFormat('ru-RU', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  })
    .format(new Date(iso))
    .replace(/\s*г\.$/, '');
}

/** Другие статьи той же рубрики — блок перелинковки под статьёй. */
export function relatedPosts(post: Post, limit = 3) {
  const sameCategory = sortedPosts.filter(
    (item) => item.slug !== post.slug && item.category === post.category,
  );
  const rest = sortedPosts.filter(
    (item) => item.slug !== post.slug && item.category !== post.category,
  );
  return [...sameCategory, ...rest].slice(0, limit);
}
