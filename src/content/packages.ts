/**
 * Тарифные пакеты для страницы /ceny/.
 *
 * Структура: три группы по услугам, в каждой три пакета от базового
 * к расширенному. Цены — за квадратный метр объекта.
 *
 * ЧТОБЫ ПОМЕНЯТЬ ЦЕНУ — правьте priceFrom нужного пакета здесь.
 * В карточках услуг на главной цены живут отдельно, в content/services.ts:
 * там указана нижняя граница — она должна совпадать с базовым пакетом.
 */

export interface PackageFeature {
  label: string;
  /** false — пункт показывается приглушённым («не входит в пакет») */
  included?: boolean;
}

export interface Package {
  number: string;
  title: string;
  priceFrom: string;
  priceUnit: string;
  features: PackageFeature[];
  duration: string;
  /** Выделенный тариф — тёмная карточка с бейджем */
  featured?: boolean;
  badge?: string;
}

export interface PackageGroup {
  /** Якорь для ссылок с первого экрана. */
  slug: string;
  /** Название услуги — заголовок блока. */
  service: string;
  /** Ссылка на подробную страницу услуги. */
  href: string;
  /** Короткая строка справа от заголовка. */
  intro: string;
  /** Развёрнутое описание услуги — абзацы перед пакетами. */
  description: string[];
  /** От чего зависит итоговая цена: самый частый вопрос на этой странице. */
  priceFactors: string[];
  packages: Package[];
}

